"""
Version Synchronization Utility

Reads the canonical version from pyproject.toml and synchronizes/checks all
downstream metadata files:
- neuralops/_version.py
- pyproject.cuda.toml
- SECURITY.md
- CITATION.cff
- README.md
- neuralops/README.md

Supports --check mode for CI quality gates.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
CANONICAL_RELEASE_DATE = "2026-11-08"


def get_canonical_version() -> str:
    pyproject_path = ROOT_DIR / "pyproject.toml"
    content = pyproject_path.read_text(encoding="utf-8")
    match = re.search(r'^version\s*=\s*["\']([^"\']+)["\']', content, re.M)
    if not match:
        raise ValueError(f"Could not find version in {pyproject_path}")
    return match.group(1)


def sync_version_py(version: str, check: bool) -> list[str]:
    version_py_path = ROOT_DIR / "neuralops" / "_version.py"
    expected = "# Generated by scripts/utils/sync_version.py. Do not edit by hand.\n" f'__version__ = "{version}"\n'
    drifts: list[str] = []
    if not version_py_path.exists():
        drifts.append(f"{version_py_path}: file does not exist")
        if not check:
            version_py_path.write_text(expected, encoding="utf-8")
        return drifts

    current = version_py_path.read_text(encoding="utf-8")
    if current != expected:
        drifts.append(f"{version_py_path}: content differs from expected generated literal")
        if not check:
            version_py_path.write_text(expected, encoding="utf-8")
    return drifts


def sync_pyproject_cuda(version: str, check: bool) -> list[str]:
    path = ROOT_DIR / "pyproject.cuda.toml"
    drifts: list[str] = []
    if not path.exists():
        return drifts
    content = path.read_text(encoding="utf-8")
    new_content = re.sub(r'^version\s*=\s*["\'][^"\']+["\']', f'version = "{version}"', content, count=1, flags=re.M)
    new_content = re.sub(r"neuralops>=[0-9a-zA-Z\.\-]+", f"neuralops>={version}", new_content)
    if new_content != content:
        drifts.append(f"{path}: version or dependency requirement out of sync with {version}")
        if not check:
            path.write_text(new_content, encoding="utf-8")
    return drifts


def sync_citation_cff(version: str, check: bool) -> list[str]:
    path = ROOT_DIR / "CITATION.cff"
    drifts: list[str] = []
    if not path.exists():
        return drifts
    content = path.read_text(encoding="utf-8")
    new_content = re.sub(r"^version:\s*.*$", f"version: {version}", content, flags=re.M)
    new_content = re.sub(r"^date-released:\s*.*$", f"date-released: {CANONICAL_RELEASE_DATE}", new_content, flags=re.M)
    if new_content != content:
        drifts.append(f"{path}: version ({version}) or date-released ({CANONICAL_RELEASE_DATE}) out of sync")
        if not check:
            path.write_text(new_content, encoding="utf-8")
    return drifts


def sync_security_md(version: str, check: bool) -> list[str]:
    path = ROOT_DIR / "SECURITY.md"
    drifts: list[str] = []
    if not path.exists():
        return drifts
    content = path.read_text(encoding="utf-8")
    major_minor = ".".join(version.split(".")[:2]) + ".x"
    expected_active_row = f"| **{major_minor}** | :white_check_mark: Active |"

    # Match and replace or prepend active row in Supported Versions table
    table_pattern = r"(\| Version \| Supported(?: \| Notes)? \|\s*\n\| :--- \| :---:?(?: \| :---)? \|\s*\n)"
    m = re.search(table_pattern, content)
    if not m:
        drifts.append(f"{path}: Supported Versions table header not found")
        return drifts

    if major_minor not in content:
        drifts.append(f"{path}: active version row missing '{expected_active_row}'")
        if not check:
            # Reconstruct table with active major.minor.x and subsequent deprecation rows
            new_table = (
                "| Version | Supported | Notes |\n"
                "| :--- | :---: | :--- |\n"
                f"| **{major_minor}** | :white_check_mark: Active | Current active production release (Unified 3-level dispatch, 203 modules, AGT suite) |\n"
                "| 2.0.x | :warning: Maintenance | Security fixes only |\n"
                "| $\\le$ 1.9.x | :x: End of Life | Upgrade to latest `v2.x` recommended |\n"
            )
            old_table_match = re.search(r"\| Version \| Supported(?: \| Notes)? \|\s*\n(?:\|[^\n]+\n)+", content)
            if old_table_match:
                content = content[: old_table_match.start()] + new_table + content[old_table_match.end() :]
                path.write_text(content, encoding="utf-8")

    # Verify canonical NeuralOps security advisory link
    stale_link = "github.com/tahamajs/SVD_linear_Attention/security/advisories/new"
    canonical_link = "github.com/tahamajs/NeuralOps/security/advisories/new"
    if stale_link in content:
        drifts.append(f"{path}: stale security advisory URL pointing to SVD_linear_Attention")
        if not check:
            content = content.replace(stale_link, canonical_link)
            path.write_text(content, encoding="utf-8")
    elif canonical_link not in content:
        drifts.append(f"{path}: canonical security advisory URL not found")

    return drifts


def sync_readme(version: str, check: bool) -> list[str]:
    path = ROOT_DIR / "README.md"
    drifts: list[str] = []
    if not path.exists():
        return drifts
    content = path.read_text(encoding="utf-8")
    new_content = re.sub(r"# 🧬 NeuralOps v\d+\.\d+\.\d+", f"# 🧬 NeuralOps v{version}", content)
    new_content = re.sub(r"badge/release-v\d+\.\d+\.\d+-blue\.svg", f"badge/release-v{version}-blue.svg", new_content)
    new_content = re.sub(r"releases/tag/v\d+\.\d+\.\d+", f"releases/tag/v{version}", new_content)
    new_content = re.sub(r"\|\s*\*\*v\d+\.\d+\.\d+\*\*\s*\(Current\)", f"| **v{version}** (Current)", new_content)
    new_content = re.sub(r"neuralops v\d+\.\d+\.\d+", f"neuralops v{version}", new_content)
    new_content = re.sub(
        r"### 🚀 GPU Verified on RTX 3090 \(v[0-9a-zA-Z\.\-]+-gpu-verified\)",
        f"### 🚀 GPU Verified on RTX 3090 (v{version}-gpu-verified)",
        new_content,
    )
    new_content = re.sub(
        r"### 🧬 NeuralOps \d+\.\d+\.\d+ Transformation Platform",
        f"### 🧬 NeuralOps {version} Transformation Platform",
        new_content,
    )
    new_content = re.sub(
        r"NeuralOps \d+\.\d+\.\d+ introduces a declarative",
        f"NeuralOps {version} introduces a declarative",
        new_content,
    )

    if new_content != content:
        drifts.append(f"{path}: version references or stale version tags out of sync with {version}")
        if not check:
            path.write_text(new_content, encoding="utf-8")
    return drifts


def sync_neuralops_readme(version: str, check: bool) -> list[str]:
    path = ROOT_DIR / "neuralops" / "README.md"
    drifts: list[str] = []
    if not path.exists():
        return drifts
    content = path.read_text(encoding="utf-8")
    new_content = re.sub(
        r"NeuralOps v[0-9\.]+",
        f"NeuralOps v{version}",
        content,
    )
    if new_content != content:
        drifts.append(f"{path}: version reference out of sync with {version}")
        if not check:
            path.write_text(new_content, encoding="utf-8")
    return drifts


def sync_examples_readme(version: str, check: bool) -> list[str]:
    path = ROOT_DIR / "examples" / "README.md"
    drifts: list[str] = []
    if not path.exists():
        return drifts
    content = path.read_text(encoding="utf-8")
    new_content = re.sub(
        r"# NeuralOps examples suite \(v[0-9\.]+\)",
        f"# NeuralOps examples suite (v{version})",
        content,
    )
    if new_content != content:
        drifts.append(f"{path}: examples suite version header out of sync with {version}")
        if not check:
            path.write_text(new_content, encoding="utf-8")
    return drifts


def sync_docs_api(version: str, check: bool) -> list[str]:
    api_dir = ROOT_DIR / "docs" / "api"
    drifts: list[str] = []
    if not api_dir.exists():
        return drifts
    for path in sorted(api_dir.glob("*.md")):
        content = path.read_text(encoding="utf-8")
        new_content = re.sub(
            r"badge/release-v\d+\.\d+\.\d+-blue\.svg",
            f"badge/release-v{version}-blue.svg",
            content,
        )
        new_content = re.sub(
            r"releases/tag/v\d+\.\d+\.\d+",
            f"releases/tag/v{version}",
            new_content,
        )
        if new_content != content:
            drifts.append(f"{path}: release badge/tag out of sync with {version}")
            if not check:
                path.write_text(new_content, encoding="utf-8")
    return drifts


def main() -> None:
    parser = argparse.ArgumentParser(description="Synchronize or check repository version metadata.")
    parser.add_argument(
        "--check", action="store_true", help="Check for drift without modifying files (exits 1 on drift)"
    )
    args = parser.parse_args()

    version = get_canonical_version()
    print(f"Canonical version (from pyproject.toml): {version}")

    all_drifts: list[str] = []
    all_drifts.extend(sync_version_py(version, check=args.check))
    all_drifts.extend(sync_pyproject_cuda(version, check=args.check))
    all_drifts.extend(sync_citation_cff(version, check=args.check))
    all_drifts.extend(sync_security_md(version, check=args.check))
    all_drifts.extend(sync_readme(version, check=args.check))
    all_drifts.extend(sync_neuralops_readme(version, check=args.check))
    all_drifts.extend(sync_examples_readme(version, check=args.check))
    all_drifts.extend(sync_docs_api(version, check=args.check))

    if args.check:
        if all_drifts:
            print(f"FAILED: Version drift detected across {len(all_drifts)} target(s):", file=sys.stderr)
            for d in all_drifts:
                print(f"  - {d}", file=sys.stderr)
            sys.exit(1)
        else:
            print("OK: All downstream version sources match canonical version.")
            sys.exit(0)
    else:
        if all_drifts:
            print(f"Successfully synchronized {len(all_drifts)} file(s):")
            for d in all_drifts:
                print(f"  - {d}")
        else:
            print("All downstream version files are already up to date.")


if __name__ == "__main__":
    main()
