"""Generate an inventory of native CUDA package layouts."""

from __future__ import annotations

from pathlib import Path


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    cuda_root = root / "neuralops" / "core" / "cuda_kernels"
    output = root / "docs" / "CUDA_PACKAGE_METADATA.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for package in sorted(path for path in cuda_root.iterdir() if path.is_dir()):
        files = {path.name for path in package.iterdir() if path.is_file()}
        cu = sorted(name for name in files if name.endswith((".cu", ".cuh")))
        binding = any(name.endswith("_binding.cpp") for name in files)
        autograd = any(name.endswith("_autograd.py") for name in files)
        init = "__init__.py" in files
        rows.append(
            f"| `{package.name}` | {'yes' if binding else 'no'} | "
            f"{'yes' if autograd else 'no'} | {'yes' if cu else 'no'} | "
            f"{'yes' if init else 'no'} | {', '.join(f'`{name}`' for name in cu) or '—'} |"
        )
    text = """# CUDA Package Metadata\n\nGenerated by `scripts/utils/generate_cuda_package_metadata.py`. A missing canonical file is intentional when the package delegates to a shared implementation or exposes a Python-only reference path.\n\n| Package | binding.cpp | autograd.py | CUDA source | __init__.py | CUDA files |\n|---|---:|---:|---:|---:|---|\n""" + "\n".join(rows) + "\n"
    output.write_text(text, encoding="utf-8")
    print(f"wrote {output} ({len(rows)} packages)")


if __name__ == "__main__":
    main()
