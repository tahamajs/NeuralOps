def update_file(mod_name):
    path = os.path.join(base_dir, f"{mod_name}.tex")
    if not os.path.exists(path):
        print(f"Error: {path} does not exist")
        return
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()

    info = data[mod_name]
    
    m_idea = re.search(r"\\subsection\*\{ایده اصلی و مبانی تئوری\}", content)
    if not m_idea:
        print(f"Could not find idea in {mod_name}")
        return
    start_pos = m_idea.start()
    
    m_bench = re.search(r"\\subsection\*\{تحلیل آماری|\\subsection\*\{کارنامه تجربی|\\subsection\*\{ارزیابی تجربی|\\subsection\*\{دستاوردها و ارزیابی|\\subsection\*\{نتایج بنچ", content)
    if not m_bench:
        print(f"No benchmark section found in {mod_name}")
        return
    end_pos = m_bench.start()
    
    new_mid = info["idea"] + "\n\n" + info["math"] + "\n\n" + info["trace"] + "\n\n\n\n"
    new_content = content[:start_pos] + new_mid + content[end_pos:]
    
    lines = new_content.split("\n")
    fixed_lines = []
    for l in lines:
        if l.strip().startswith("%"):
            fixed_lines.append(l)
        else:
            l_fixed = l.replace(r"\%", "٪").replace("%", "٪")
            l_fixed = l_fixed.replace(r"\\_", r"\_")
            fixed_lines.append(l_fixed)
    new_content = "\n".join(fixed_lines)

    with open(path, "w", encoding="utf-8") as f:
        f.write(new_content)
    print(f"Successfully updated {mod_name}.tex")

for m in data:
    update_file(m)
