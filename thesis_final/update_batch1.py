def clean_lr(text):
    # Escape unescaped underscores inside \lr{...}
    def repl(m):
        inner = m.group(1)
        # replace any _ not preceded by \ with \_
        fixed = re.sub(r'(?<!\\)_', r'\\_', inner)
        return f"\\lr{{{fixed}}}"
    return re.sub(r'\\lr\{([^}]+)\}', repl, text)

def fix_module(name, data):
    path = f"/Users/tahamajs/Documents/uni/Project/thesis_final/attentions_latex/individual_modules/{name}.tex"
    if not os.path.exists(path):
        print(f"File not found: {path}")
