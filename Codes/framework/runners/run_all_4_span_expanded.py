def run_model(m: dict) -> dict:
    out_dir = RESULTS_BASE / m["slug"]
    out_dir.mkdir(parents=True, exist_ok=True)

    cmd = [
        sys.executable,
        "-u",
        str(SWEEP_SCRIPT),
        "--model",
        m["model_path"],
        "--model_family",
        m["family"],
        "--dataset",
        "sst2",
        "--dataset_dir",
        str(DATASET_DIR),
        "--output_dir",
        str(out_dir),
        "--modules",
        MODULE_KEY,
        "--batch_size",
        "8",
        "--recovery_steps",
        "50",
        "--timeout",
        "1200",
        "--precision",
        "fp16",
        "--defer_export",
        "--fresh",
    ] + EXTRA_ARGS

    ckpt = m.get("parent_checkpoint")
    if ckpt and Path(ckpt).exists():
        cmd += ["--parent_checkpoint", ckpt]

    logger.info("Starting %-14s …", m["name"])
    t0 = time.time()
    proc = subprocess.run(cmd)
    elapsed = time.time() - t0
    logger.info("Finished %-14s  %.1fs  exit=%d", m["name"], elapsed, proc.returncode)

    row_data: dict = {}
    csv_path = out_dir / "summary.csv"
    if csv_path.exists():
        try:
            with csv_path.open(encoding="utf-8") as cf:
                for row in csv.DictReader(cf):
                    if row.get("module_name") == MODULE_KEY:
                        row_data = row
                        break
        except Exception as exc:
            logger.warning("Could not parse %s: %s", csv_path, exc)

    status = row_data.get("status", "FAIL" if proc.returncode != 0 else "UNKNOWN")
    try:
        acc = float(row_data.get("accuracy_pct") or 0.0)
    except (ValueError, TypeError):
        acc = 0.0

    return {
        "name": m["name"],
        "slug": m["slug"],
        "family": m["family"],
        "out_dir": out_dir,
        "exit_code": proc.returncode,
        "status": status,
        "accuracy_pct": acc,
        "elapsed_s": elapsed,
        "row_data": row_data,
    }


