import uuid
from django.db import models
from django.conf import settings


class ExperimentMemory(models.Model):
    """
    A vector embedding of an experiment stored in ChromaDB.
    This model tracks the ChromaDB document ID so we can retrieve it.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    run = models.OneToOneField(
        'experiment.TrainingRun',
        on_delete=models.CASCADE,
        related_name='memory_entry'
    )
    chroma_id = models.CharField(max_length=100, unique=True)
    summary_text = models.TextField(
        help_text="Human-readable summary used to generate the embedding"
    )
    embedding_model = models.CharField(max_length=100, default='all-MiniLM-L6-v2')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"Memory for {self.run.name or self.run.id}"


class AnalysisResult(models.Model):
    """
    A periodic analysis result generated by the AI Research Coach.
    """
    ANALYSIS_TYPES = [
        ('cluster', 'Experiment Clustering'),
        ('trend', 'Trend Detection'),
        ('suggestion', 'Actionable Suggestion'),
        ('motivation', 'Motivational Insight'),
        ('summary', 'Periodic Summary'),
    ]
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='analysis_results'
    )
    analysis_type = models.CharField(max_length=20, choices=ANALYSIS_TYPES)
    title = models.CharField(max_length=300)
    content = models.TextField()
    metadata = models.JSONField(default=dict, blank=True)
    is_read = models.BooleanField(default=False)
    is_archived = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.analysis_type}: {self.title}"


class Recommendation(models.Model):
    """
    A personalised recommendation generated by the AI Coach.
    """
    RECOMMENDATION_TYPES = [
        ('hyperparameter', 'Hyperparameter Tuning'),
        ('architecture', 'Architecture Change'),
        ('attention', 'Attention Mechanism'),
        ('compression', 'Compression Strategy'),
        ('dataset', 'Dataset Suggestion'),
        ('next_experiment', 'Next Experiment'),
        ('paper', 'Paper to Read'),
    ]
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='coach_recommendations'
    )
    recommendation_type = models.CharField(max_length=30, choices=RECOMMENDATION_TYPES)
    title = models.CharField(max_length=300)
    description = models.TextField()
    confidence = models.FloatField(default=0.5)
    action_data = models.JSONField(default=dict, blank=True,
                                   help_text="Pre-filled experiment config for one-click launch")
    is_applied = models.BooleanField(default=False)
    is_dismissed = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return self.title


class ChatSession(models.Model):
    """
    A conversation session with the AI Research Coach.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='coach_chat_sessions'
    )
    title = models.CharField(max_length=300, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-updated_at']

    def __str__(self):
        return f"Chat with {self.user.username} ({self.created_at.strftime('%Y-%m-%d')})"


class ChatMessage(models.Model):
    """
    A single message in a chat session.
    """
    ROLE_CHOICES = [
        ('user', 'User'),
        ('assistant', 'Assistant'),
        ('system', 'System'),
    ]
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    session = models.ForeignKey(
        ChatSession,
        on_delete=models.CASCADE,
        related_name='messages'
    )
    role = models.CharField(max_length=10, choices=ROLE_CHOICES)
    content = models.TextField()
    metadata = models.JSONField(default=dict, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['created_at']

    def __str__(self):
        return f"{self.role}: {self.content[:50]}"