import uuid

from django.conf import settings
from django.db import models


class AgentSession(models.Model):
    """A conversation session with the research agent."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="agent_sessions",
    )
    title = models.CharField(max_length=300, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-updated_at"]

    def __str__(self):
        return f"Session {self.id.hex[:8]} by {self.user.username}"


class AgentMessage(models.Model):
    """A message in an agent session."""

    ROLE_CHOICES = [("user", "User"), ("assistant", "Assistant"), ("system", "System")]
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    session = models.ForeignKey(
        AgentSession, on_delete=models.CASCADE, related_name="messages"
    )
    role = models.CharField(max_length=10, choices=ROLE_CHOICES)
    content = models.TextField()
    metadata = models.JSONField(default=dict, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at"]


class ResearchMemory(models.Model):
    """
    Long‑term memory stored in a vector database (ChromaDB).
    This model holds a local reference to the external document ID.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="research_memories",
    )
    chroma_doc_id = models.CharField(max_length=200, unique=True)
    content = models.TextField()
    metadata = models.JSONField(default=dict, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]


class GeneratedIdea(models.Model):
    """An idea or suggestion generated by the agent for a user."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="generated_ideas",
    )
    title = models.CharField(max_length=300)
    description = models.TextField()
    idea_type = models.CharField(
        max_length=50,
        choices=[
            ("experiment", "Experiment"),
            ("collaboration", "Collaboration"),
            ("paper", "Paper Topic"),
            ("improvement", "Improvement"),
            ("compression", "Compression Strategy"),
        ],
    )
    is_saved = models.BooleanField(default=False)
    metadata = models.JSONField(default=dict, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
