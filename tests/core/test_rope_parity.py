"""Tests for numerical parity between neuralops.core.utils.rope and HuggingFace Transformers."""

from __future__ import annotations

import pytest
import torch

from neuralops.core.utils.rope import apply_rotary_pos_emb, broadcast_cos_sin, rotate_half


def _hf_rotate_half(x: torch.Tensor) -> torch.Tensor:
    """HuggingFace Transformers reference rotate_half."""
    x1 = x[..., : x.shape[-1] // 2]
    x2 = x[..., x.shape[-1] // 2 :]
    return torch.cat((-x2, x1), dim=-1)


def _hf_apply_rotary_pos_emb(
    q: torch.Tensor,
    k: torch.Tensor,
    cos: torch.Tensor,
    sin: torch.Tensor,
    unsqueeze_dim: int = 1,
) -> tuple[torch.Tensor, torch.Tensor]:
    """HuggingFace Transformers reference apply_rotary_pos_emb."""
    cos = cos.unsqueeze(unsqueeze_dim)
    sin = sin.unsqueeze(unsqueeze_dim)
    q_embed = (q * cos) + (_hf_rotate_half(q) * sin)
    k_embed = (k * cos) + (_hf_rotate_half(k) * sin)
    return q_embed, k_embed


def test_rotate_half_parity() -> None:
    """Verify rotate_half matches HuggingFace reference for even head_dim."""
    x = torch.randn(2, 4, 16, 64)
    out_neuralops = rotate_half(x)
    out_hf = _hf_rotate_half(x)
    assert torch.equal(out_neuralops, out_hf)


def test_apply_rotary_pos_emb_hf_parity() -> None:
    """Verify apply_rotary_pos_emb bit-exact parity with HuggingFace Transformers reference."""
    B, H, T, D = 2, 8, 32, 64
    torch.manual_seed(42)
    q = torch.randn(B, H, T, D)
    k = torch.randn(B, H, T, D)

    # Cos and sin shaped as [B, T, D] as generated by rotary embeddings
    cos = torch.randn(B, T, D)
    sin = torch.randn(B, T, D)

    q_ref, k_ref = _hf_apply_rotary_pos_emb(q, k, cos, sin, unsqueeze_dim=1)
    q_out, k_out = apply_rotary_pos_emb(q, k, cos, sin)

    torch.testing.assert_close(q_out, q_ref, rtol=1e-6, atol=1e-6)
    torch.testing.assert_close(k_out, k_ref, rtol=1e-6, atol=1e-6)


def test_apply_rotary_pos_emb_dtype_preservation() -> None:
    """Verify float16 and bfloat16 dtypes are preserved without upcasting to float32."""
    B, H, T, D = 1, 4, 16, 32
    for dtype in [torch.float16, torch.bfloat16]:
        q = torch.randn(B, H, T, D, dtype=dtype)
        k = torch.randn(B, H, T, D, dtype=dtype)
        cos = torch.randn(B, T, D, dtype=torch.float32)  # cos often computed in fp32
        sin = torch.randn(B, T, D, dtype=torch.float32)

        q_out, k_out = apply_rotary_pos_emb(q, k, cos, sin)
        assert q_out.dtype == dtype, f"Expected {dtype}, got {q_out.dtype}"
        assert k_out.dtype == dtype, f"Expected {dtype}, got {k_out.dtype}"


def test_apply_rotary_pos_emb_partial_rotary() -> None:
    """Verify partial rotary embedding when rotary_dim < head_dim."""
    B, H, T, D = 2, 4, 16, 64
    rotary_dim = 32
    q = torch.randn(B, H, T, D)
    k = torch.randn(B, H, T, D)
    cos = torch.randn(B, T, rotary_dim)
    sin = torch.randn(B, T, rotary_dim)

    q_out, k_out = apply_rotary_pos_emb(q, k, cos, sin)
    assert q_out.shape == (B, H, T, D)
    assert k_out.shape == (B, H, T, D)
    # The unrotated tail must remain unchanged
    assert torch.equal(q_out[..., rotary_dim:], q[..., rotary_dim:])
    assert torch.equal(k_out[..., rotary_dim:], k[..., rotary_dim:])


def test_apply_rotary_pos_emb_none_safeguard() -> None:
    """Verify None cos/sin safely returns unmutated tensors."""
    q = torch.randn(2, 4, 16, 64)
    k = torch.randn(2, 4, 16, 64)
    q_out, k_out = apply_rotary_pos_emb(q, k, None, None)
    assert q_out is q
    assert k_out is k


def test_apply_rotary_pos_emb_position_ids() -> None:
    """Verify position_ids correctly indexes 2D cos/sin table."""
    max_seq, D = 128, 64
    table_cos = torch.randn(max_seq, D)
    table_sin = torch.randn(max_seq, D)

    position_ids = torch.tensor([[5, 10, 15, 20]])  # shape (1, 4)
    q = torch.randn(1, 2, 4, D)
    k = torch.randn(1, 2, 4, D)

    q_out, k_out = apply_rotary_pos_emb(q, k, table_cos, table_sin, position_ids=position_ids)
    assert q_out.shape == q.shape
    assert k_out.shape == k.shape


def test_apply_rotary_pos_emb_gradient_flow() -> None:
    """Verify gradient flows back through query and key tensors."""
    q = torch.randn(2, 2, 8, 16, requires_grad=True)
    k = torch.randn(2, 2, 8, 16, requires_grad=True)
    cos = torch.randn(2, 8, 16)
    sin = torch.randn(2, 8, 16)

    q_out, k_out = apply_rotary_pos_emb(q, k, cos, sin)
    loss = q_out.sum() + k_out.sum()
    loss.backward()

    assert q.grad is not None and not torch.isnan(q.grad).any()
    assert k.grad is not None and not torch.isnan(k.grad).any()
