"""Results command family: results, ledger, recipe, evidence, ops."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from neuralops.cli.core.errors import ExitCode
from neuralops.cli.core.output import CliReporter


def handle_results(args: argparse.Namespace) -> int:
    """Summarize, query, or export benchmark results and master ledger records."""
    # Check if this invocation is for the master ledger sub-features
    has_ledger_flags = any([
        getattr(args, "dossier", None),
        getattr(args, "diff", None),
        getattr(args, "sync", False),
        getattr(args, "delete", False),
        getattr(args, "add", False),
        getattr(args, "plot", None),
    ])

    if has_ledger_flags:
        return handle_ledger(args)

    from neuralops.benchmarks.api import Runner
    reporter = CliReporter(
        quiet=getattr(args, "quiet", False),
        verbose=getattr(args, "verbose", False),
        json_mode=getattr(args, "json", False),
    )

    out_dir = getattr(args, "output_dir", "results/latest")
    runner = Runner(output_dir=out_dir)
    df = runner.summary()
    if df.empty:
        reporter.log(f"No results found in {out_dir}")
        return int(ExitCode.SUCCESS)

    fmt = getattr(args, "format", "table")
    if getattr(args, "json", False) or fmt == "json":
        reporter.print_json(df.to_dict(orient="records"))
    elif fmt in ("latex", "markdown", "csv"):
        from neuralops.core.paper_export import export_benchmark_table
        records = df.to_dict(orient="records")
        out = export_benchmark_table(
            records=records,
            format=fmt,
            caption="Benchmark summary results generated by NeuralOps v1.4.0.",
            label="tab:neuralops_summary_results",
            highlight_best=True,
            mark_pareto=True,
        )
        print(out)
    else:
        print(df.to_string(index=False))
    return int(ExitCode.SUCCESS)


def handle_ledger(args: argparse.Namespace) -> int:
    """Query, inspect, diff, sync, and mutate master results SQLite ledger."""
    from neuralops.core.results_ledger import ResultRecord, get_default_ledger
    reporter = CliReporter(
        quiet=getattr(args, "quiet", False),
        verbose=getattr(args, "verbose", False),
        json_mode=getattr(args, "json", False),
    )

    ledger = get_default_ledger()

    if getattr(args, "dossier", None):
        dossier = ledger.get_module_dossier(args.dossier)
        if not dossier:
            reporter.log(f"[-] No dossier found for module '{args.dossier}'.")
            return int(ExitCode.MODULE_NOT_FOUND)
        reporter.print_json(dossier)
        return int(ExitCode.SUCCESS)

    if getattr(args, "diff", None):
        diff_res = ledger.compare_versions(args.diff, rev_a=args.rev_a, rev_b=args.rev_b)
        reporter.print_json(diff_res)
        return int(ExitCode.SUCCESS)

    if getattr(args, "sync", False):
        reporter.log("[+] Syncing Results Ledger...")
        ledger.rewrite_jsonl_from_sqlite()
        reporter.log("[✓] Master ledger rewritten and synchronized.")
        return int(ExitCode.SUCCESS)

    if getattr(args, "delete", False):
        rec_ids = [args.id] if getattr(args, "id", None) else None
        count = ledger.delete_records(
            record_ids=rec_ids,
            module_name=getattr(args, "module", None),
            category=getattr(args, "category", None),
            version_tag=getattr(args, "version_tag", None),
            hard_delete=getattr(args, "hard", False),
        )
        mode_str = "hard purged" if getattr(args, "hard", False) else "soft deleted"
        reporter.log(f"[✓] Successfully {mode_str} {count} record(s).")
        return int(ExitCode.SUCCESS)

    if getattr(args, "add", False):
        if not getattr(args, "module", None):
            reporter.log("[-] --module is required when using --add.")
            return int(ExitCode.INVALID_CONFIG)
        metrics = json.loads(args.metrics) if getattr(args, "metrics", None) else {}
        setup = json.loads(args.setup) if getattr(args, "setup", None) else {}
        if getattr(args, "dataset", None):
            setup["dataset"] = args.dataset
        if getattr(args, "backbone", None):
            setup["backbone"] = args.backbone
        rec = ledger.add_or_replace(
            ResultRecord(
                record_id="",
                module_name=args.module,
                category=getattr(args, "category", None) or "attention",
                family=getattr(args, "family", None) or "general",
                version_tag=getattr(args, "version_tag", None) or "v1.4.0",
                generation_method={"algorithm": getattr(args, "method", None) or "CLI Entry"},
                experimental_setup=setup,
                metrics=metrics,
            ),
            mode=getattr(args, "mode", "archive_old"),
        )
        reporter.log(f"[✓] Record stored: {rec.record_id} (Rev {rec.revision}, Status: {rec.status})")
        return int(ExitCode.SUCCESS)

    records = ledger.query(
        module_name=getattr(args, "module", None),
        category=getattr(args, "category", None),
        family=getattr(args, "family", None),
        dataset=getattr(args, "dataset", None),
        backbone=getattr(args, "backbone", None),
        method_contains=getattr(args, "method", None),
        git_sha=getattr(args, "git_sha", None),
        version_tag=getattr(args, "version_tag", None),
        only_active=not getattr(args, "all_revisions", False),
        limit=getattr(args, "limit", 50),
    )

    if getattr(args, "plot", None):
        plot_res = ledger.plot_results(
            records,
            chart_type=args.plot,
            x_metric=getattr(args, "x_metric", None),
            y_metric=getattr(args, "y_metric", None),
            output_path=getattr(args, "out", None),
        )
        print(plot_res["ascii"])
        if plot_res.get("svg_path"):
            reporter.log(f"[✓] Vector chart saved to '{plot_res['svg_path']}'.")
        return int(ExitCode.SUCCESS)

    fmt = "markdown" if getattr(args, "format", "table") == "table" else getattr(args, "format", "markdown")
    output_str = ledger.export_table(records, format=fmt)
    if getattr(args, "out", None):
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(output_str)
        reporter.log(f"[✓] Table exported to '{args.out}'.")
    else:
        print(output_str)
    return int(ExitCode.SUCCESS)


def handle_recipe(args: argparse.Namespace) -> int:
    """Dispatches declarative recipe pipeline commands."""
    action = getattr(args, "recipe_action", None)
    if not action:
        print("Usage: neuralops recipe {plan,execute,validate,diff,evidence,benchmark} ...")
        return int(ExitCode.USAGE_ERROR)

    from neuralops.recipe.loader import load_recipe
    if action == "plan":
        from neuralops.pipeline_transform.planner import plan_recipe
        rec = load_recipe(args.file)
        plan = plan_recipe(rec)
        print(f"Recipe '{rec.metadata.name}' v{rec.metadata.version}: {len(plan.stages)} stage(s) planned.")
        for idx, stage in enumerate(plan.stages):
            mutations = stage.contract.declares_mutations if stage.contract else []
            print(f"  [{idx}] {stage.id} ({stage.operation_type}@{stage.version}, mutates={mutations})")
        return int(ExitCode.SUCCESS)

    elif action == "execute":
        from neuralops.pipeline_transform.executor import execute_plan
        from neuralops.pipeline_transform.planner import plan_recipe
        from neuralops.reporting.report import render_report
        rec = load_recipe(args.file)
        plan = plan_recipe(rec)
        device = getattr(args, "device", "auto")
        stop_on_error = getattr(args, "stop_on_error", True)
        res = execute_plan(plan, device=device, stop_on_error=stop_on_error)
        print(f"Transformation status: {res.status.value} (Stages: {len(res.stages)}, Elapsed: {res.total_time_seconds:.2f}s)")
        if hasattr(res, "evidence") and res.evidence is not None:
            print("\n" + render_report(res.evidence))
        return int(ExitCode.SUCCESS) if res.status.value == "SUCCESS" else int(ExitCode.INTERNAL_ERROR)

    elif action == "validate":
        from neuralops.validator.static import validate_recipe_static
        rec = load_recipe(args.file)
        try:
            warnings = validate_recipe_static(rec)
            print(f"✓ Recipe '{rec.metadata.name}' is valid (all 15 static well-formedness rules passed).")
            if warnings:
                print(f"  Warnings ({len(warnings)}):")
                for w in warnings:
                    print(f"   - {w}")
            return int(ExitCode.SUCCESS)
        except Exception as e:
            print(f"✗ Recipe validation failed: {e}")
            return int(ExitCode.GATE_VERIFICATION_FAILED)

    elif action == "diff":
        rec1 = load_recipe(args.file1)
        rec2 = load_recipe(args.file2)
        print(f"Structural Diff: '{rec1.metadata.name}' vs '{rec2.metadata.name}'")
        print(f"  Operations: {len(rec1.operations)} -> {len(rec2.operations)}")
        return int(ExitCode.SUCCESS)

    elif action == "evidence":
        from neuralops.reporting.evidence import load_evidence
        from neuralops.reporting.report import render_report
        ev = load_evidence(args.file)
        print(render_report(ev))
        return int(ExitCode.SUCCESS)

    elif action == "benchmark":
        import torch
        from neuralops.benchmarks.parallel_benchmark import DataParallelBenchmark
        from neuralops.benchmarks.recipe_benchmark import run_recipe_benchmark
        from neuralops.distributed.context import DistributedContext

        parallel_flag = bool(getattr(args, "parallel", False))
        parallel_bench = None
        if parallel_flag:
            ctx = DistributedContext()
            parallel_bench = DataParallelBenchmark(ctx)

        device = getattr(args, "device", "auto")
        if device == "auto":
            device = "cuda" if torch.cuda.is_available() else "cpu"

        results = run_recipe_benchmark(
            recipe=args.file,
            device=device,
            repeats=getattr(args, "repeats", 3),
            batch_size=getattr(args, "batch_size", 2),
            seq_len=getattr(args, "seq_len", 16),
            parallel_benchmark=parallel_bench,
        )
        print(f"Recipe Benchmark '{results['recipe_name']}' completed (device={results['device']}, speedup={results['comparison']['speedup']:.2f}x):")
        print(json.dumps(results, indent=2))
        return int(ExitCode.SUCCESS)

    return int(ExitCode.SUCCESS)


def handle_evidence(args: argparse.Namespace) -> int:
    """Dispatches evidence inspection commands."""
    action = getattr(args, "evidence_action", None)
    if action == "show":
        from neuralops.reporting.evidence import load_evidence
        from neuralops.reporting.report import render_report
        ev = load_evidence(args.file)
        print(render_report(ev))
        return int(ExitCode.SUCCESS)
    print("Usage: neuralops evidence show <evidence.json>")
    return int(ExitCode.USAGE_ERROR)


def handle_ops(args: argparse.Namespace) -> int:
    """Dispatches operation contract registry inspection."""
    action = getattr(args, "ops_action", None)
    if action == "list" or action is None:
        from neuralops.operations.registry import list_operations
        ops = list_operations()
        print(f"Registered Operations ({len(ops)}):")
        for op in ops:
            print(f"  - {op}")
        return int(ExitCode.SUCCESS)
    return int(ExitCode.SUCCESS)
