"""LaTeX Table Generator for NeuralOps publication-grade booktabs output."""

from __future__ import annotations

import hashlib
import sqlite3

import pandas as pd


class LatexTableGenerator:
    """Generates camera-ready LaTeX booktabs tables directly from DataFrame or SQLite."""

    def __init__(self, commit_sha: str = "8e1c23bc", hardware_target: str = "NVIDIA RTX 3090 (24GB)") -> None:
        self.commit_sha = commit_sha
        self.hardware_target = hardware_target

    def generate_from_dataframe(
        self,
        df: pd.DataFrame,
        caption: str = "Master Efficiency Leaderboard Across Attention Architectures",
        label: str = "tab:master_efficiency",
    ) -> str:
        """Generate LaTeX booktabs string from a pandas DataFrame."""
        sha = hashlib.sha256(df.to_csv(index=False).encode("utf-8")).hexdigest()[:16]

        col_align = "l" + "c" * (len(df.columns) - 1)
        header = " & ".join([f"\\textbf{{{col}}}" for col in df.columns]) + " \\\\"

        rows = []
        for _, row in df.iterrows():
            formatted_vals = []
            for val in row.values:
                if isinstance(val, (float, int)):
                    formatted_vals.append(f"{val:.2f}" if isinstance(val, float) else str(val))
                else:
                    formatted_vals.append(str(val))
            rows.append(" & ".join(formatted_vals) + " \\\\")

        body = "\n".join(rows)
        latex_code = (
            f"% Auto-generated by NeuralOps LatexTableGenerator\n"
            f"% Git Commit SHA: {self.commit_sha}\n"
            f"% Data SHA-256 Provenance: {sha}\n"
            f"% Hardware Target: {self.hardware_target}\n"
            f"\\begin{{table}}[t]\n"
            f"\\centering\n"
            f"\\small\n"
            f"\\caption{{{caption}}}\n"
            f"\\label{{{label}}}\n"
            f"\\begin{{tabular}}{{{col_align}}}\n"
            f"\\toprule\n"
            f"{header}\n"
            f"\\midrule\n"
            f"{body}\n"
            f"\\bottomrule\n"
            f"\\end{{tabular}}\n"
            f"\\end{{table}}"
        )
        return latex_code

    def generate_from_sqlite(
        self,
        db_path: str,
        query: str,
        caption: str = "Master Benchmark Query",
        label: str = "tab:benchmark_query",
    ) -> str:
        """Extract data from SQLite database and render LaTeX table."""
        conn = sqlite3.connect(db_path)
        try:
            df = pd.read_sql_query(query, conn)
        finally:
            conn.close()
        return self.generate_from_dataframe(df, caption=caption, label=label)
